#data parser function
#takes the raw output of the measuring machine and converts it toa usable data frame format
read_od_plates <- function(path) {
  
  # 1. Reading the file
  #Each line of the text file is read separately and gets put into character vector
  #this is needed because the raw data is not in a data frame format so it's tricky to read
  lines <- read_lines(path)
  
  # 2. Finding the measurements
  #all different measurements start with "Field Group", algorithm looks for this
  #'start_lines' variable stores the line numbers of where the data starts for all strains measured
  #including the 'Plate ID' that names the bacterial strain
  #regex generated by AI. since I don't speak that language very well :p
  start_lines <- which(str_detect(lines, regex("^\\s*Field\\s+Group\\s*$", ignore_case = TRUE)))
    
  #the end of all the data blocks is simpler
  #they all end 1 line before the next begins
  #this way the end line is always the start line minus 1
  #-1 vector index ignores the first start line, as that is line 1, there is no data before it :p
  #the it extracts 1 from each stats line to mark the previous sections' end line
  end_lines <- c(start_lines[-1] - 1, length(lines))
  

  # 3. separating each measurement block
  #map2() applies the created local funtion to its 2 values (start and end number)
  #not a fan of purrr functions, but it does the job....
  #also contains a huge code chunk
  measurements <- map2(
    .x = start_lines, 
    .y = end_lines, 
    .f = function(start, end) {
      
      block <- lines[start:end]
      
      #failure function for error messages
      #not my own idea
      #stops the function fro working and reports the location
      fail <- function(message) {
        stop(
          paste0("Block beginning at line ", start, ": ", message),
          call. = FALSE
        )
      }
    
    
    # 4. extracting the strain names
    #regex finds the lines that contains 'Plate ID'
    id_pattern <- regex("^\\s*Plate\\s+ID\\s*:\\s*", ignore_case = TRUE)
    
    #returns the number of the line that has the plate id aka. the strain name
    id_line <- block[str_detect(block, id_pattern)]
    
    #getting the strain name
    #removing the label and the white space
    #thank you stringR for the useful functions
    strain <- id_line |> 
      str_remove(id_pattern) |> 
      str_trim()
    
    
    # 5. extracting the plate rows
    #keep only the lines that start with a letter [A-P] followed by a tab
    #these lines mark the actual lines of data
    data_rows <- block[str_detect(block, "^\\s*[A-P]\\t")]
    
    #split all the data at the tabs
    #splits the lines of data into individual measurements
    #map applies a white-space trim too all created values
    fields <- str_split(data_rows, fixed("\t")) |> 
      map(str_trim)
    
    
    # 6. Checking the plate structure for any errors
    #proved surprisingly useful during testing
    #a 'correct' plate must have 16 rows [A-P]
    #a 'correct' row must have 26(!) fields:
    #   1 row label [A-P], 24 OD values + 1 Wavelength value
    if (length(fields) != 16L || any(lengths(fields) != 26L)) {
      fail("Expected 16 rows, each with 24 OD cells and a wavelength.")
    }
    
    # 7. Building the actual OD table
    #keeping only column 1-25 (row label + 24 measurements)
    #26th row is ignore (wavelenght tracker)
    #each row becomes a separate 1-row tall tibble
    #map_dfr the combines them into a single data frame
    plate <- map_dfr(fields, function(x) {
      as_tibble_row(set_names(x[1:25], c("row", as.character(1:24))))
    })
    
    #8. converts the OD values from text to numbers
    #applies parse_double to ever column Except the row labels (-row)
    #empty cell become NA
    plate <- plate |>
      mutate(across(-row, ~ parse_double(.x, na = c("", "NA"))))
    
    
    # 9. Assigning the row names
    #turns the 'row' column into actual row names
    plate <- plate |> 
      column_to_rownames("row")
    
    #returns the strain name and its table
    list(strain = strain, plate = plate)
    
    
  }) #closing the map2 and the included functions
  
  # 10. Naming the tables
  #repeated measurements of the same strain are marked with _1 and _2
  table_names <- tibble(
    strain = map_chr(measurements, "strain")) |>
    group_by(strain) |>
    mutate(table_name = if (n() > 1L) {
      str_c(strain, "_", row_number())
    } else {strain
        }) |>
    ungroup() |>
    pull(table_name)
  
  #return the different table as a named list
  measurements |> 
    map("plate") |> 
    set_names(table_names)

}

#palte splitter
split_384_plate <- function(plate) {
  
  #during the splitting each small plate takes the second row and second column of the large table
  #this way the 384 gets split in 4
  
  #specifying the starting points
  #the large plate "scanner" goes 1/1, 1/2, 2/1, 2/2
  row_start <- c(1, 1, 2, 2)
  col_start <- c(1, 2, 1, 2)
  
  #more purrr map (=lapply) to pair up starting rows and columns
  map2(row_start, col_start, function(row_start, col_start) {
    
    #selecting every second row and every second column
    selected_rows <- seq(row_start, 16, by = 2)
    selected_column <- seq(col_start, 24, by = 2)
    
    #extracting the selected rows and column from the OG plate
    small_plate <- plate[selected_rows, selected_column]
    
    #renaming the smaller plate's rows and columns from the GO one to new one
    #rows A-H and columns 1-12
    rownames(small_plate) <- LETTERS[1:8] #just learned about 'LETTERs' today
    colnames(small_plate) <- as.character(1:12)
    
    small_plate
    
  }) |> #pipe into the naming section
    
    #giving a name to the 4 small plates
    set_names(str_c("plate", 1:4))
  
}


#importing the data and creating save location ================

#select the data to be worked with
working_data <- file.choose()


#choose save location folder for exporting the final data and images
output_dir <- choose.dir(caption = "Select a save folder")

#extracting date of measurement
#basename removes all parts of a directory but the last (aka. the file name)
measurement_date <- working_data |> 
  basename() |> 
  str_remove(pattern = "\\.txt$")

#creating a new folder in the save location based on measurement date
save_folder <- file.path(output_dir, measurement_date)

dir.create(save_folder, showWarnings = FALSE)


#parsing the data from the raw output file
od_tables <- read_od_plates(working_data)

#splitting the data into 4 smaller plates
#optional flattening, but I don't like it all that much, might make further work harder 
#still kept it, might help simplify code later
od_tables_96 <- od_tables |> 
  map(split_384_plate) |> 
  list_flatten(name_spec = "{outer}_{inner}")


#assigning the additives to the correct measurements =================

#importing the 96 well plate layout reference table
#choose the location of 'plate layout.xlsx
  #   Idea: put the function in a custom package along with this table a constant for easier reference
  #   This section the becomes obsolete
layout_path <- file.choose()

#importing from the spreadsheet
layout_wide <- read_excel(path = layout_path, 
                          sheet = 1, range = "A1:M9", 
                          col_names = F,
                          col_types = "text")
#remove header
layout_wide <- layout_wide[-1, ]

#assigning the correct row labels
names(layout_wide) <- c("Row", as.character(1:12))

#converting the grid into one row per well
layout_referece <- layout_wide |> 
  mutate(Row = str_trim(Row)) |> 
  pivot_longer(cols = -Row,
               names_to = "Column",
               values_to = "Additive") |> 
  mutate(Column  = as.integer(Column), #this is important for later function
         Additive = str_trim(Additive)) #this removes the space before '-'


#turning the od_tables_96 into a long format
od_measurements_long <- imap_dfr(od_tables_96, function(plate, table_name) {
  
  plate |> 
    rownames_to_column(var = "Row") |> 
    pivot_longer(cols = -Row,
                 names_to = "Column",
                 values_to = "OD") |>  #makes it the same layout as the reference above
    mutate(Column = as.integer(Column)) |> 
    
           #Defining the 'plate position'
    mutate(Plate_num = as.integer(str_extract(table_name, "[1-4]$")),
          
            #naming the strain used in the measurement
            Strain = str_remove(table_name, "_plate[1-4]$"))
    
})

#pairing up the measurements with the correct additive based on well position
od_additives <- od_measurements_long |> 
  left_join(y = layout_referece,
            by = c("Row", "Column"))

#pivoting to resemble the final data frame
#Keeping the well positio markers for now
#in case it might be needed (I don't think so)
od_with_well_pos <- od_additives |> 
  pivot_wider(names_from = Strain,
              values_from = OD) |> 
  arrange(Plate_num, Row, Column)


#creating the well type descriptors
#'empty' wells on plate 1,2,3 are empty 'strain' wells'
#'empty' wells on palte 4 are 'additive_background'
#'-' wells are 'frame'
#'the rest, aka. additive well on plate 1,2,3 are 'additive'
#'getting the order right was tricky :p
od_table_wide <- od_with_well_pos |> 
  mutate(well_type = case_when(Additive == "-" ~ "frame",
                               Plate_num == 4 ~ "additive_background",
                               Additive == "empty" & Plate_num %in% 1:3 ~ "strain",
                               !is.na(Additive) & Plate_num %in% 1:3 ~ "additive",
                               .default = NA_character_), .after = Additive)



#saving this middle od table in case it's needed
write_csv(x = od_table_wide, file = file.path(save_folder, paste0("plate_", measurement_date, ".csv")))


